(function () {
  var STORAGE_KEY = 'qa_lang';
  var DEFAULT_LANG = 'ru';
  var currentLang = DEFAULT_LANG;

  function getDict(lang) {
    return QA_TRANSLATIONS[lang] || QA_TRANSLATIONS[DEFAULT_LANG];
  }

  function langFromPath(pathname) {
    var seg = (pathname || '').split('/')[1];
    return QA_TRANSLATIONS[seg] ? seg : null;
  }

  function applyLanguage(lang, opts) {
    if (!QA_TRANSLATIONS[lang]) lang = DEFAULT_LANG;
    var dict = getDict(lang);
    currentLang = lang;

    var updateUrl = !opts || opts.updateUrl !== false;
    if (updateUrl && window.history && window.history.pushState) {
      var path = '/' + lang;
      if (window.location.pathname !== path) {
        var newUrl = path + window.location.search + window.location.hash;
        try {
          if (opts && opts.replace) {
            window.history.replaceState({ lang: lang }, '', newUrl);
          } else {
            window.history.pushState({ lang: lang }, '', newUrl);
          }
        } catch (e) { /* pushState is blocked on file:// and some sandboxed origins */ }
      }
    }

    document.documentElement.setAttribute('lang', lang);

    if (dict['meta.title']) document.title = dict['meta.title'];
    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && dict['meta.description']) metaDesc.setAttribute('content', dict['meta.description']);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key] != null) el.textContent = dict[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (dict[key] != null) el.innerHTML = dict[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] != null) el.setAttribute('placeholder', dict[key]);
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria');
      if (dict[key] != null) el.setAttribute('aria-label', dict[key]);
    });

    document.querySelectorAll('.lang-overlay__option').forEach(function (btn) {
      btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
    });

    var toggleCode = document.getElementById('lang-toggle-code');
    if (toggleCode) toggleCode.textContent = lang.toUpperCase();

    refreshStatNumbers(lang);

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
  }

  function refreshStatNumbers(lang) {
    var localeMap = { ru: 'ru-RU', az: 'az-Latn-AZ', en: 'en-US' };
    var locale = localeMap[lang] || 'ru-RU';
    document.querySelectorAll('.stat__num').forEach(function (el) {
      if (el.textContent.trim() === '0') return; // not animated yet — the count-up will use the right locale
      var target = parseInt(el.getAttribute('data-count'), 10) || 0;
      el.textContent = target.toLocaleString(locale);
    });
  }

  function t(key, vars) {
    var dict = getDict(currentLang);
    var str = dict[key] != null ? dict[key] : key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = str.replace('{' + k + '}', vars[k]);
      });
    }
    return str;
  }

  function detectInitialLang() {
    var fromPath = langFromPath(window.location.pathname);
    if (fromPath) return fromPath;

    var saved;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) { /* ignore */ }
    if (saved && QA_TRANSLATIONS[saved]) return saved;
    return DEFAULT_LANG;
  }

  // On the very first load, sync the URL to match the resolved language
  // without adding a history entry (replace, not push).
  applyLanguage(detectInitialLang(), { replace: true });

  window.addEventListener('popstate', function () {
    applyLanguage(langFromPath(window.location.pathname) || DEFAULT_LANG, { updateUrl: false });
  });

  /* ---------- Full-screen language overlay ---------- */
  var overlay = document.getElementById('lang-overlay');
  var toggleBtn = document.getElementById('lang-toggle');
  var closeBtn = document.getElementById('lang-overlay-close');

  function openOverlay() {
    if (!overlay) return;
    overlay.classList.add('is-open');
    document.body.classList.add('lang-overlay-open');
  }

  function closeOverlay() {
    if (!overlay) return;
    overlay.classList.remove('is-open');
    document.body.classList.remove('lang-overlay-open');
  }

  if (toggleBtn) toggleBtn.addEventListener('click', openOverlay);
  if (closeBtn) closeBtn.addEventListener('click', closeOverlay);

  if (overlay) {
    overlay.addEventListener('click', function (e) {
      if (e.target === overlay) closeOverlay();
    });
    overlay.querySelectorAll('.lang-overlay__option').forEach(function (btn) {
      btn.addEventListener('click', function (e) {
        e.preventDefault();
        applyLanguage(btn.getAttribute('data-lang'));
        closeOverlay();
      });
    });
  }

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') closeOverlay();
  });

  window.QA_I18N = {
    t: t,
    setLang: applyLanguage,
    get lang() { return currentLang; }
  };
})();
